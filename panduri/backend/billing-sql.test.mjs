import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
// Pass PGLITE_MODULE only when running outside a package that already provides @electric-sql/pglite.
const { PGlite } = await import(process.env.PGLITE_MODULE || '@electric-sql/pglite');
const uid='12345678-1234-1234-1234-123456789abc';
test('Postgres billing functions: idempotency, bans, stale events, server premium and client permissions', async () => {
 const db=new PGlite();
 await db.exec(`create role anon; create role authenticated; create role service_role;
 create schema auth;
 create table auth.users(id uuid primary key);
 create function auth.uid() returns uuid language sql stable as $$ select '${uid}'::uuid $$;
 create table public.profiles(id uuid primary key references auth.users, vip_until timestamptz, plan text, premium_banned boolean not null default false, display_name text);
 create function public.is_owner() returns boolean language sql stable as $$ select false $$;
 create table public.purchases(id bigint generated always as identity primary key,user_id uuid references auth.users,provider text,product text,status text,expires_at timestamptz,created_at timestamptz default now());
 grant usage on schema public, auth to authenticated;
 grant select on public.profiles to authenticated;
 grant update(display_name) on public.profiles to authenticated;
 insert into auth.users values('${uid}'); insert into public.profiles(id) values('${uid}');`);
 for(const migration of ['202611080001_payments.sql','202611080002_multiplatform_billing.sql']) await db.exec(await readFile(new URL('supabase/migrations/'+migration,import.meta.url),'utf8'));
 await db.exec(`insert into public.billing_orders(id,provider,provider_id,user_id,plan,amount,currency) values('11111111-1111-1111-1111-111111111111','tbc','order1','${uid}','monthly',14.99,'GEL');`);
 const fulfill=`select public.fulfill_web_purchase('tbc','order1','${uid}','monthly')`;
 await db.exec(fulfill);
 const before=(await db.query(`select vip_until from public.profiles`)).rows[0].vip_until;
 await Promise.all([db.exec(fulfill),db.exec(fulfill)]);
 assert.deepEqual((await db.query(`select vip_until from public.profiles`)).rows[0].vip_until,before);
 assert.equal((await db.query('select count(*)::int as n from public.purchases')).rows[0].n,1);
 await assert.rejects(db.exec(`select public.fulfill_web_purchase('tbc','unknown','${uid}','monthly')`),/unknown order/);
 await db.exec(`update public.profiles set premium_banned=true; insert into public.billing_orders(id,provider,provider_id,user_id,plan,amount,currency) values('22222222-2222-2222-2222-222222222222','paypal','order2','${uid}','yearly',49.99,'USD'); select public.fulfill_web_purchase('paypal','order2','${uid}','yearly');`);
 assert.deepEqual((await db.query('select vip_until from public.profiles')).rows[0].vip_until,before);
 assert.equal((await db.query(`select public.is_premium('${uid}') as active`)).rows[0].active,false);
 await db.exec(`select public.sync_store_entitlement('${uid}','2090-01-01',200); select public.sync_store_entitlement('${uid}',null,100);`);
 assert.ok((await db.query('select store_until from public.profiles')).rows[0].store_until);
 await db.exec(`update public.profiles set premium_banned=false,vip_until=null;`);
 assert.equal((await db.query(`select public.is_premium('${uid}') as active`)).rows[0].active,true);
 await db.exec(`select public.sync_store_entitlement('${uid}',null,300);`);
 assert.equal((await db.query(`select public.is_premium('${uid}') as active`)).rows[0].active,false);
 await db.exec('set role authenticated');
 await assert.rejects(db.exec(fulfill),/permission denied/);
 await assert.rejects(db.exec(`select public.sync_store_entitlement('${uid}','2099-01-01',1000)`),/permission denied/);
 await assert.rejects(db.exec(`update public.profiles set store_until='2099-01-01'`),/permission denied/);
 await assert.rejects(db.exec(`insert into public.billing_orders(id) values(gen_random_uuid())`),/permission denied/);
 await db.close();
});
